"use strict";

const fs = require("node:fs/promises");
const path = require("node:path");
const { build } = require("esbuild");

const GAME_ROOT = path.resolve(__dirname, "..", "..", "..", "..");
const SOURCE_PATH = path.join(GAME_ROOT, "engine", "content-v2", "pack-resolver-source.js");
const OUTPUT_PATH = path.join(GAME_ROOT, "engine", "content-v2", "generated", "pack-resolver.cjs");
const CHECK_MODE = process.argv.includes("--check");

main().catch((error) => {
  process.stderr.write(`${error?.stack || error}\n`);
  process.exitCode = 1;
});

async function main() {
  const result = await build({
    entryPoints: [SOURCE_PATH], bundle: true, platform: "node", format: "cjs", target: ["node22"],
    nodePaths: [path.resolve(__dirname, "..", "node_modules")],
    legalComments: "none", sourcemap: false, write: false, logLevel: "silent",
    banner: { js: "/* AUTO-GENERATED by build-content-v2-resolver.js. DO NOT EDIT. */" },
  });
  const output = result.outputFiles?.[0]?.text;
  if (!output) throw new Error("Pack resolver bundling produced no output.");
  if (CHECK_MODE) {
    const current = await fs.readFile(OUTPUT_PATH, "utf8").catch(() => "");
    if (current !== output) throw new Error("Generated Pack resolver is missing or stale. Run npm run build:content-v2.");
    process.stdout.write("Generated Pack resolver is current.\n");
    return;
  }
  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, output, "utf8");
  process.stdout.write(`Generated ${path.relative(GAME_ROOT, OUTPUT_PATH)}.\n`);
}
