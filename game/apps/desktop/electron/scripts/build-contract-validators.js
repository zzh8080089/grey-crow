"use strict";

const fs = require("node:fs/promises");
const path = require("node:path");
const Ajv2020 = require("ajv/dist/2020").default;
const standaloneCode = require("ajv/dist/standalone").default;
const { build } = require("esbuild");

const GAME_ROOT = path.resolve(__dirname, "..", "..", "..", "..");
const CONTRACT_ROOT = path.join(GAME_ROOT, "engine", "contracts", "v2");
const SCHEMA_ROOT = path.join(CONTRACT_ROOT, "schemas");
const REGISTRY_PATH = path.join(CONTRACT_ROOT, "schema-registry.json");
const OUTPUT_PATH = path.join(CONTRACT_ROOT, "generated", "validators.cjs");
const CHECK_MODE = process.argv.includes("--check");

main().catch((error) => {
  process.stderr.write(`${error?.stack || error}\n`);
  process.exitCode = 1;
});

async function main() {
  const output = await compileValidators();
  if (CHECK_MODE) {
    const current = await fs.readFile(OUTPUT_PATH, "utf8").catch(() => "");
    if (current !== output) {
      throw new Error("Generated contract validators are missing or stale. Run npm run build:contracts.");
    }
    process.stdout.write("Contract validators are current.\n");
    return;
  }

  await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, output, "utf8");
  process.stdout.write(`Generated ${path.relative(GAME_ROOT, OUTPUT_PATH)}.\n`);
}

async function compileValidators() {
  const registry = JSON.parse(await fs.readFile(REGISTRY_PATH, "utf8"));
  validateRegistry(registry);

  const schemaFiles = (await fs.readdir(SCHEMA_ROOT))
    .filter((name) => name.endsWith(".schema.json"))
    .sort();
  const schemas = [];
  const schemasByFile = new Map();
  for (const file of schemaFiles) {
    const schema = JSON.parse(await fs.readFile(path.join(SCHEMA_ROOT, file), "utf8"));
    schemas.push(schema);
    schemasByFile.set(file, schema);
  }

  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    validateSchema: true,
    coerceTypes: false,
    removeAdditional: false,
    useDefaults: false,
    code: { source: true, lines: true },
  });
  for (const schema of schemas) {
    ajv.addSchema(schema);
  }

  const exportMap = {};
  for (const entry of registry.contracts) {
    const schema = schemasByFile.get(entry.file);
    if (!schema) {
      throw new Error(`Contract schema file ${entry.file} is missing.`);
    }
    const declaredVersion = schema.properties?.schemaVersion?.const;
    if (declaredVersion !== entry.schemaVersion) {
      throw new Error(`Contract ${entry.contractId} schemaVersion does not match the registry.`);
    }
    exportMap[entry.exportName] = schema.$id;
    if (!ajv.getSchema(schema.$id)) {
      throw new Error(`Contract schema ${schema.$id} did not compile.`);
    }
  }

  const standalone = standaloneCode(ajv, exportMap);
  const result = await build({
    absWorkingDir: path.resolve(__dirname, ".."),
    stdin: {
      contents: standalone,
      resolveDir: path.resolve(__dirname, ".."),
      sourcefile: "grey-crow-contract-validators.generated.js",
      loader: "js",
    },
    bundle: true,
    platform: "node",
    format: "cjs",
    target: ["node22"],
    legalComments: "none",
    sourcemap: false,
    write: false,
    logLevel: "silent",
    banner: {
      js: "/* AUTO-GENERATED by build-contract-validators.js. DO NOT EDIT. */",
    },
  });
  if (!result.outputFiles?.[0]) {
    throw new Error("Contract validator bundling produced no output.");
  }
  return result.outputFiles[0].text;
}

function validateRegistry(registry) {
  if (!registry || !Array.isArray(registry.contracts) || registry.contracts.length === 0) {
    throw new Error("Contract schema registry is empty or invalid.");
  }
  const ids = new Set();
  const versions = new Set();
  const exports = new Set();
  for (const entry of registry.contracts) {
    for (const [label, value, set] of [
      ["contractId", entry.contractId, ids],
      ["schemaVersion", entry.schemaVersion, versions],
      ["exportName", entry.exportName, exports],
    ]) {
      if (!value || set.has(value)) {
        throw new Error(`Contract registry has an invalid or duplicate ${label}.`);
      }
      set.add(value);
    }
  }
}
