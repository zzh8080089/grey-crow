"use strict";

const { contextBridge, ipcRenderer } = require("electron");

// Do not forward the ErrorEvent, rejected value, DOM node or resource URL.
const recordProblem = code => { void ipcRenderer.invoke("grey-crow:record-renderer-problem", { code }).catch(() => {}); };
window.addEventListener("error", event => recordProblem(event.target === window ? "RENDERER_SCRIPT_ERROR" : "RENDERER_RESOURCE_ERROR"), true);
window.addEventListener("unhandledrejection", () => recordProblem("RENDERER_PROMISE_ERROR"));

